/** Insight ids served by an element key on a workspace (for data-run11-insight). */
export function insightIdsFor(ws: string, placementIds: string[], key: string): string[] {
  return Object.entries(INSIGHT_MAP).filter(([id, i]) => id.startsWith(`${ws}-BI-`) && i.served.some((s) => placementIds.includes(s) || s === key || `kpi:r11-${s.toLowerCase()}` === key || `chart:r11-${s.toLowerCase()}` === key || `run11q:r11-${s.toLowerCase()}` === key)).map(([id]) => id);
}
