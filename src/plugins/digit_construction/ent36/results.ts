/**
 * Builds the owner's result files for the Construction × Enterprise final product run from the live source:
 *   docs/construction/ent36/DIGIT_CON_ENT_WORK_LIST_RESULT.csv — every work-list row with Status, Where in code, Test and
 *   result, plus the 26 ENTERPRISE_NEEDS rows (ENT-NEED-01…26) — and docs/construction/ENTERPRISE_36X3_SUMMARY.md.
 * Pure: ent36worklist.test.ts [ENT36-W-FILES] compares them with the committed files (ENT36_WRITE=1 rewrites them),
 * so the result never drifts from the code.
 */
import * as W from "./worklist";
import * as C from "./csv";
import { R19_WORKSPACES } from "../r19/workspaces";
import { DEPT_NAMES, deptBySlug } from "../r19/wsIndex";

export function buildResults(input: string, ctx: W.WCtx): { csv: string; summary: string; counts: { rows: number; done: number; blocked: number } } {
  const grid = C.parseCsv(input);
  const head = grid[0]!; const S = head.length - 3;
  type Out = { id: string; type: string; dept: string; status: string; where: string; test: string };
  const outs: Out[] = []; const body: string[][] = [];
  const deptOf = (where: string, fallback = "00") => { const m = /\/construction\/([a-z-]+)\//.exec(where); const d = m ? deptBySlug(m[1]!) : undefined; if (d) return d;
    const dt = R19_WORKSPACES.find((w) => w.docs.some((x) => where.includes(x.doctype)))?.id; return dt ? dt.slice(0, 2) : fallback; };
  for (const r of grid.slice(1)) {
    const rec = Object.fromEntries(head.map((k, i) => [k, r[i] ?? ""])) as unknown as W.WRow;
    const res = W.classify(rec, ctx);
    if (res.unresolved) throw new Error(`unresolved ${rec.ID}: ${res.unresolved}`);
    const where = res.status === "BLOCKED" ? `Reason: ${res.where}` : res.where;
    const m = /^(?:WS|UXKPI|PLC-SCR)-(\d\d)/.exec(rec.ID);
    const dept = m ? m[1]! : deptOf(res.where);
    body.push([...r.slice(0, S), res.status, where, res.test]);
    outs.push({ id: rec.ID, type: rec.Type, dept, status: res.status, where, test: res.test });
  }
  for (const [id, need, status, where, test] of W.ENT_NEEDS) {
    const row = head.map(() => ""); row[head.indexOf("ID")] = id; row[head.indexOf("Idea")] = need; row[head.indexOf("Type")] = "enterprise need (test run ENTERPRISE_NEEDS.md)";
    row[head.indexOf("Sheet")] = "ENTERPRISE_NEEDS.md"; row[S] = status; row[S + 1] = status === "BLOCKED" ? `Reason: ${where}` : where; row[S + 2] = test;
    body.push(row); outs.push({ id, type: "enterprise need", dept: "00", status, where, test });
  }
  const csv = C.toCsv([head, ...body]);

  const work = outs.filter((o) => o.type !== "enterprise need");
  const count = (xs: Out[], s: string) => xs.filter((x) => x.status === s).length;
  const done = work.filter((o) => o.status !== "BLOCKED").length;
  const L: string[] = [];
  L.push("# DIGIT Construction × Enterprise — 36 × 3 final product summary", "",
    `Generated by \`src/plugins/digit_construction/ent36/results.ts\` (ENT36_WRITE=1 bunx vitest run src/plugins/digit_construction/ent36worklist.test.ts) from the live source (row checks: \`src/plugins/digit_construction/ent36worklist.test.ts\`). Result file: \`docs/construction/ent36/DIGIT_CON_ENT_WORK_LIST_RESULT.csv\`.`, "",
    `**Work list: ${work.length} rows — ${done} done (ALREADY_PRESENT ${count(work, "ALREADY_PRESENT")}, COMPLETED ${count(work, "COMPLETED")}), BLOCKED ${count(work, "BLOCKED")}.** BUILT is not used separately: the 8 sheet-16 BUILD documents are counted as COMPLETED.`, "",
    "Shape: 9 departments × 4 workspaces × 3 tabs (Overview / Documents & Work / Full Reports) at `/construction/<department>/<workspace>/<tab>`; documents at `/construction/doc/<doctype>/<name>`; every old `/plugins/digit_construction/…` link redirects. Section contract `contract.py` CONTRACT_VERSION 3 (36 section keys, 144 KPI slots).", "",
    "## Per department", "", "| Dept | Workspaces live | Rows | ALREADY_PRESENT | COMPLETED | BLOCKED |", "|---|---|---|---|---|---|");
  for (const d of ["01", "02", "03", "04", "05", "06", "07", "08", "09", "00"]) {
    const xs = work.filter((o) => o.dept === d); const ws = R19_WORKSPACES.filter((w) => w.dept === d).length;
    L.push(`| ${d === "00" ? "Shared / cross-department" : `${d} ${DEPT_NAMES[d]?.[0] ?? ""}`} | ${d === "00" ? "11 shared screens (SCR-00)" : `${ws} / 4`} | ${xs.length} | ${count(xs, "ALREADY_PRESENT")} | ${count(xs, "COMPLETED")} | ${count(xs, "BLOCKED")} |`);
  }
  L.push("", "## Per row type", "", "| Type | Rows | ALREADY_PRESENT | COMPLETED | BLOCKED |", "|---|---|---|---|---|");
  for (const t of [...new Set(work.map((o) => o.type))]) { const xs = work.filter((o) => o.type === t); L.push(`| ${t} | ${xs.length} | ${count(xs, "ALREADY_PRESENT")} | ${count(xs, "COMPLETED")} | ${count(xs, "BLOCKED")} |`); }
  L.push("", "## BLOCKED rows (exact reason)", "", "| ID | Type | Reason |", "|---|---|---|");
  for (const o of work.filter((x) => x.status === "BLOCKED")) L.push(`| ${o.id} | ${o.type} | ${o.where.replace(/^Reason: /, "").replace(/\|/g, "/")} |`);
  const needs = outs.filter((o) => o.type === "enterprise need");
  L.push("", `## Test-run Enterprise needs (ENT-NEED-01…26) — ${needs.filter((n) => n.status !== "BLOCKED").length}/26 placed, ${count(needs, "BLOCKED")} blocked`, "", "| ID | Status | Where |", "|---|---|---|");
  for (const n of needs) L.push(`| ${n.id} | ${n.status} | ${n.where.replace(/\|/g, "/")} |`);
  L.push("", "## Owner rulings applied in this run", "",
    "- **Routes**: Construction opens under `/construction/…`; no `/plugins/…` in a visible URL; old links redirect (src/lib/appUrls.ts + urls.ts).",
    "- **DEC-015**: no automatic Desk User; an app opens only for a user holding one of its roles (Pro / HR / Construction `enterprise.roles`); a user with no app role sees only Home. The 7 feature rows blocked by DEC-015 in TEST_RESULTS.csv pass under this ruling.",
    "- **P10** revenue / WIP basis: seeded Undefined; WIP adjustments stay report-only drafts (Post refused) until Finance defines it. P2 retention account and P5 tolerances stay Finance values (empty = draft / report only).",
    "- **MAP-2071**: Percent Complete is a Percent column.",
    "- **Server package items (recorded, not built here)**: ENT-NEED-12 daily compliance scheduler; ENT-NEED-16 server doc_events for Purchase Order, Material Request, Stock Entry and Payment Entry.",
    "- No direct GL / Stock Ledger / Payment Ledger writes; only native documents post.", "");
  return { csv, summary: L.join("\n"), counts: { rows: work.length, done, blocked: count(work, "BLOCKED") } };
}
