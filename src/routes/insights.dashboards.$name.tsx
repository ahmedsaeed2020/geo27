import { createFileRoute, Link } from "@tanstack/react-router";
import { adapter, useStoreVersion } from "@/lib/adapter";
import { InsightsShell, ServerTag } from "@/components/insights/InsightsShell";
import { DashboardGrid } from "@/components/insights/DashboardGrid";

export const Route = createFileRoute("/insights/dashboards/$name")({
  head: () => ({ meta: [{ title: "Dashboard — Insights · Digit Virtual Core" }, { name: "description", content: "Insights dashboard with live filters over local query results." }, { property: "og:title", content: "Insights Dashboard" }, { property: "og:description", content: "Insights dashboard with live filters over local query results." }, { property: "og:type", content: "website" }, { name: "twitter:card", content: "summary" }] }),
  component: DashboardPage,
});

/** dashboard/Dashboard.vue — view mode with filters; editing happens in the workbook. */
function DashboardPage() {
  useStoreVersion();
  const { name } = Route.useParams();
  const d = adapter.get("Insights Dashboard v3", name);
  return (
    <InsightsShell header={<><span className="text-lg font-semibold">{String(d?.["title"] ?? name)}</span><div className="ms-auto flex items-center gap-2">
      {d && <Link to="/insights/workbook/$workbookName/dashboard/$dashboardName" params={{ workbookName: String(d["workbook"]), dashboardName: name }} className="crm-input w-auto">Edit</Link>}
      <ServerTag title="Public share links and preview images are generated by the server">Share</ServerTag></div></>}>
      <div className="p-5">{d ? <DashboardGrid key={String(d["modified"])} dash={d} /> : <p className="text-sm text-crm-muted">Dashboard not found.</p>}</div>
    </InsightsShell>
  );
}
