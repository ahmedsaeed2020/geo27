/**
 * Shared source relation mechanism (DIGIT-CORE-PRO-UX-006 B1) — one implementation for every "related documents" surface
 * (form Connections tab, DIGIT Document 360 panels). Ports of the Frappe rules that decide what counts as related:
 *
 *  - frappe.desk.notifications.get_open_count: a dashboard transaction is matched on `non_standard_fieldnames[dt]`
 *    or the dashboard `fieldname`;
 *  - frappe.utils.data.get_filter: when that field is NOT on the linked DocType's header, Frappe looks for it in the
 *    DocType's child tables (e.g. Sales Invoice ← Sales Order through Sales Invoice Item.sales_order), so a parent counts
 *    once when any of its rows points at the document;
 *  - Dynamic Link fields (Payment Entry Reference.reference_name + reference_doctype) only match rows whose type field
 *    names the source DocType;
 *  - frappe.desk.notifications.get_internal_links: `internal_links` are UPSTREAM documents named in this document's own
 *    child rows (Sales Order ← Quotation through items.prevdoc_docname).
 *  - when a DocType declares neither `links` nor a dashboard, the reverse Link-field index is used: the generated
 *    catalog index plus the enabled apps' own Link fields (reverseLinksFor), so app DocTypes list their downstream records.
 *
 * Reads are permission-scoped through session.ts (filterReadable / hasPerm); an unreadable DocType is reported as
 * "denied" and an unknown definition as "unavailable" — never as a zero. Nothing here writes records.
 */
import { queryOptions } from "@tanstack/react-query";
import { adapter, type Doc } from "./adapter";
import { cachedMeta, TABLE_TYPES, type DashboardDef, type DocTypeMeta } from "./catalog";
import type { Filter } from "./desk";
import { ADMIN, currentUser, filterReadable, hasPerm } from "./session";
import { readLimitedFor } from "./scope";
import { enabledPlugins } from "@/plugins/runtime";

export type RevLink = { link_doctype: string; link_fieldname: string; child: string | null };
/** Generated by scripts/extract-reverse-links.py: Link fields pointing at each DocType (frappe linked_with discovery). */
export const reverseLinksQuery = queryOptions({
  queryKey: ["catalog-reverse-links"],
  queryFn: async () => (await fetch("/catalog/reverse_links.json")).json() as Promise<{ doctypes: Record<string, RevLink[]> }>,
  staleTime: Infinity,
});

type ReverseIndex = Record<string, RevLink[]>;
const nativeParents = new WeakMap<ReverseIndex, Map<string, Set<string>>>();
/** Native child table → parent DocTypes, read from the generated index's child-row entries (no hand-written list). */
function parentsFromIndex(ix: ReverseIndex | undefined): Map<string, Set<string>> {
  if (!ix) return new Map();
  let m = nativeParents.get(ix);
  if (!m) {
    m = new Map();
    for (const rows of Object.values(ix)) for (const r of rows) if (r.child) { const s = m.get(r.child) ?? new Set<string>(); s.add(r.link_doctype); m.set(r.child, s); }
    nativeParents.set(ix, m);
  }
  return m;
}
/** Parent DocTypes that hold a native child table in a Table field (child-table register, owner 2026-11-13 §2f). */
export function childParents(child: string, ix?: ReverseIndex): string[] { return [...(parentsFromIndex(ix).get(child) ?? [])].sort(); }

/**
 * Link fields of the ENABLED apps (plugin DocTypes, their child tables and Custom Fields — the same manifests the meta
 * overlay applies) that point at `target`, in the generated index's shape. The frozen reverse_links.json only knows
 * catalog DocTypes, so without this an app DocType never lists the documents that link to it. Derived from manifests
 * at call time, so disabling an app removes its entries and the Original index stays untouched.
 */
export function appReverseLinks(target: string, ix?: ReverseIndex): RevLink[] {
  const ps = enabledPlugins();
  const own = new Map<string, { istable: boolean; fields: { fieldname?: string; fieldtype: string; options?: string }[] }>();
  // Single (settings) DocTypes hold one record and are never a list of related documents (frappe linked_with skips them)
  for (const p of ps) for (const d of p.doctypes ?? []) if (!d.issingle) own.set(d.name, { istable: !!d.istable, fields: d.fields as { fieldname?: string; fieldtype: string; options?: string }[] });
  const customs = ps.flatMap((p) => p.custom_fields ?? []);
  const native = parentsFromIndex(ix);
  const parentsOf = (child: string): string[] => {
    const s = new Set<string>(native.get(child) ?? []);
    for (const [name, d] of own) if (!d.istable && d.fields.some((f) => TABLE_TYPES.has(f.fieldtype) && f.options === child)) s.add(name);
    for (const c of customs) if (TABLE_TYPES.has(c.fieldtype) && c.options === child) s.add(c.dt);
    return [...s];
  };
  const out: RevLink[] = [];
  const put = (link_doctype: string, link_fieldname: string, child: string | null) => {
    if (!out.some((r) => r.link_doctype === link_doctype && r.link_fieldname === link_fieldname && r.child === child)) out.push({ link_doctype, link_fieldname, child });
  };
  const place = (dt: string, field: string, isChild: boolean) => {
    if (isChild) parentsOf(dt).forEach((par) => put(par, field, dt));
    else put(dt, field, null);
  };
  for (const [name, d] of own) for (const f of d.fields) if (f.fieldname && f.fieldtype === "Link" && f.options === target) place(name, f.fieldname, d.istable);
  for (const c of customs) if (c.fieldname && c.fieldtype === "Link" && c.options === target) place(c.dt, c.fieldname, own.get(c.dt)?.istable ?? native.has(c.dt));
  return out;
}

/** Reverse Link index of `target`: generated catalog entries plus the enabled apps' Link fields (appReverseLinks). */
export function reverseLinksFor(target: string, ix?: ReverseIndex): RevLink[] {
  const base = ix?.[target] ?? [];
  // sorted by holder like the generated index (scripts/extract-reverse-links.py), so the order is stable across apps
  const extra = appReverseLinks(target, ix).filter((r) => !base.some((b) => b.link_doctype === r.link_doctype && b.link_fieldname === r.link_fieldname))
    .sort((a, b) => a.link_doctype.localeCompare(b.link_doctype));
  return extra.length ? [...base, ...extra] : base;
}

type MetaOf = (doctype: string) => DocTypeMeta | undefined;
const fieldOf = (m: DocTypeMeta | undefined, f: string) => m?.fields.find((x) => x.fieldname === f);

export type RelationPath =
  | { match: "header"; dynamicType?: string | undefined }
  | { match: "child"; tables: { field: string; child: string; dynamicType?: string | undefined }[] }
  /** Definition not loaded: header value OR any child row value matches (same result when the field exists once). */
  | { match: "any" };

/** Where `fieldname` lives on `linkDoctype` (frappe.utils.data.get_filter child-table resolution). */
export function relationPath(linkDoctype: string, fieldname: string, metaOf: MetaOf = cachedMeta): RelationPath {
  const m = metaOf(linkDoctype);
  if (!m) return { match: "any" };
  const own = fieldOf(m, fieldname);
  if (own) return { match: "header", dynamicType: own.fieldtype === "Dynamic Link" ? String(own.options ?? "") || undefined : undefined };
  const tables: { field: string; child: string; dynamicType?: string | undefined }[] = [];
  for (const df of m.fields) {
    if (!df.fieldname || !TABLE_TYPES.has(df.fieldtype) || !df.options) continue;
    const cm = metaOf(String(df.options));
    const cf = cm ? fieldOf(cm, fieldname) : undefined;
    // child definition not loaded: keep the table as a candidate (rows are inspected for the field)
    if (!cm || cf) tables.push({ field: df.fieldname, child: String(df.options), dynamicType: cf?.fieldtype === "Dynamic Link" ? String(cf.options ?? "") || undefined : undefined });
  }
  return tables.length ? { match: "child", tables } : { match: "any" };
}

const rowsOfTable = (d: Doc, field: string): Record<string, unknown>[] => (Array.isArray(d[field]) ? (d[field] as Record<string, unknown>[]).filter((r) => !!r && typeof r === "object") : []);
const anyChildRows = (d: Doc): Record<string, unknown>[] => Object.values(d).flatMap((v) => (Array.isArray(v) ? (v as unknown[]).filter((r): r is Record<string, unknown> => !!r && typeof r === "object") : []));

/** Records of `linkDoctype` related to `sourceDoctype`/`name` through `fieldname` (distinct parents; no permission filter). */
export function linkedRows(linkDoctype: string, fieldname: string, sourceDoctype: string, name: string, opts: { metaOf?: MetaOf; rows?: Doc[] } = {}): { rows: Doc[]; path: RelationPath } {
  const path = relationPath(linkDoctype, fieldname, opts.metaOf ?? cachedMeta);
  const all = opts.rows ?? adapter.list(linkDoctype);
  const hit = (r: Record<string, unknown>, dyn?: string) => r[fieldname] === name && (!dyn || !r[dyn] || r[dyn] === sourceDoctype);
  let rows: Doc[];
  if (path.match === "header") rows = all.filter((d) => hit(d, path.dynamicType));
  else if (path.match === "child") rows = all.filter((d) => path.tables.some((t) => rowsOfTable(d, t.field).some((r) => hit(r, t.dynamicType))));
  else rows = all.filter((d) => hit(d) || anyChildRows(d).some((r) => hit(r)));
  return { rows, path };
}

export type RelationStatus = "ok" | "limited" | "denied" | "unavailable";
export interface RelationCount {
  status: RelationStatus;
  /** Readable related records (0 when denied/unavailable — the status, not the number, is what callers show). */
  rows: Doc[];
  count: number;
  /** List filter that opens exactly these records in the native list (child matches open by name). */
  filters: Filter[];
  path: RelationPath;
}

/**
 * Permission-scoped related records: readable rows only (frappe get_open_count runs get_list with permissions).
 * "limited" comes from the user's own permission rules (only-if-creator / User Permission), never from comparing with
 * hidden rows, so a count never reveals that records the user cannot read exist.
 */
export function relationCount(linkDoctype: string, fieldname: string, sourceDoctype: string, name: string, user = currentUser(), metaOf: MetaOf = cachedMeta): RelationCount {
  const { rows, path } = linkedRows(linkDoctype, fieldname, sourceDoctype, name, { metaOf });
  const filtersFor = (rs: Doc[]): Filter[] => (path.match === "header" ? [[fieldname, "=", name]] : [["name", "in", rs.map((r) => r.name)]]);
  if (user === ADMIN) return { status: "ok", rows, count: rows.length, filters: filtersFor(rows), path };
  const m = metaOf(linkDoctype);
  if (!m) return { status: "unavailable", rows: [], count: 0, filters: [], path };
  if (!hasPerm(m, "read", undefined, user)) return { status: "denied", rows: [], count: 0, filters: [], path };
  const readable = filterReadable(m, rows, user);
  return { status: readLimitedFor(m, user) ? "limited" : "ok", rows: readable, count: readable.length, filters: filtersFor(readable), path };
}

/** Upstream documents named in this document's own fields/rows (frappe get_internal_links): `spec` is "field" or [table, field]. */
export function internalLinkNames(doc: Doc, spec: unknown): string[] {
  const out = new Set<string>();
  if (typeof spec === "string") { const v = doc[spec]; if (typeof v === "string" && v) out.add(v); }
  else if (Array.isArray(spec) && spec.length >= 2) for (const r of rowsOfTable(doc, String(spec[0]))) { const v = r[String(spec[1])]; if (typeof v === "string" && v) out.add(v); }
  return [...out];
}

export type ConnectionKind = "doctype-links" | "dashboard" | "internal" | "reverse";
export interface ConnectionItem { link_doctype: string; link_fieldname: string; kind: ConnectionKind; child?: string | null; internal?: unknown }
export interface ConnectionGroup { label: string; items: ConnectionItem[] }

/**
 * Connection groups of a DocType, in Frappe's precedence: DocType `links` (JSON), the `_dashboard.py` transactions
 * (internal links marked as upstream), then — only when neither exists — the generated reverse Link-field index.
 */
export function connectionGroups(meta: DocTypeMeta, dash: DashboardDef | undefined, reverse: RevLink[] | undefined): ConnectionGroup[] {
  const groups = new Map<string, ConnectionItem[]>();
  const add = (label: string, it: ConnectionItem) => { const g = groups.get(label) ?? []; if (!g.some((x) => x.link_doctype === it.link_doctype)) g.push(it); groups.set(label, g); };
  meta.links.forEach((l) => add(l.group || "Related", { link_doctype: l.link_doctype, link_fieldname: l.link_fieldname, kind: "doctype-links" }));
  dash?.transactions.forEach((t) => t.items.forEach((it) => {
    const internal = (dash.internal_links as Record<string, unknown> | undefined)?.[it];
    add(t.label || "Related", internal !== undefined
      ? { link_doctype: it, link_fieldname: "", kind: "internal", internal }
      : { link_doctype: it, link_fieldname: dash.non_standard_fieldnames[it] ?? dash.fieldname ?? "", kind: "dashboard" });
  }));
  if (!meta.links.length && !dash) (reverse ?? []).forEach((r) => add("Linked With", { link_doctype: r.link_doctype, link_fieldname: r.link_fieldname, kind: "reverse", child: r.child }));
  return [...groups.entries()].map(([label, items]) => ({ label, items }));
}

/** Count for one connection item of `doc` (internal links count the upstream names this document references). */
export function connectionCount(it: ConnectionItem, sourceDoctype: string, doc: Doc, user = currentUser(), metaOf: MetaOf = cachedMeta): RelationCount {
  if (it.kind === "internal") {
    const names = internalLinkNames(doc, it.internal);
    const existing = names.map((n) => adapter.get(it.link_doctype, n)).filter((d): d is Doc => !!d);
    const m = metaOf(it.link_doctype);
    const base = { filters: [["name", "in", existing.map((d) => d.name)]] as Filter[], path: { match: "any" } as RelationPath };
    if (user === ADMIN) return { ...base, status: "ok", rows: existing, count: existing.length };
    if (!m) return { ...base, status: "unavailable", rows: [], count: 0, filters: [] };
    if (!hasPerm(m, "read", undefined, user)) return { ...base, status: "denied", rows: [], count: 0, filters: [] };
    const readable = filterReadable(m, existing, user);
    return { status: readLimitedFor(m, user) ? "limited" : "ok", rows: readable, count: readable.length, filters: [["name", "in", readable.map((d) => d.name)]], path: base.path };
  }
  if (!it.link_fieldname) return { status: "unavailable", rows: [], count: 0, filters: [], path: { match: "any" } };
  return relationCount(it.link_doctype, it.link_fieldname, sourceDoctype, doc.name, user, metaOf);
}

export interface OutgoingLink { doctype: string; names: string[]; field: string; label: string; table?: string | undefined }
/** Documents this document points at: header Link / Dynamic Link fields and child-row Link fields (source documents). */
export function outgoingLinks(doc: Doc, meta: DocTypeMeta, metaOf: MetaOf = cachedMeta): OutgoingLink[] {
  const out = new Map<string, OutgoingLink>();
  const put = (doctype: string, name: unknown, field: string, label: string, table?: string) => {
    if (typeof name !== "string" || !name || !doctype) return;
    const k = `${doctype}|${table ?? ""}|${field}`;
    const cur = out.get(k) ?? { doctype, names: [], field, label, table };
    if (!cur.names.includes(name)) cur.names.push(name);
    out.set(k, cur);
  };
  const scan = (m: DocTypeMeta, row: Record<string, unknown>, table?: string) => {
    for (const f of m.fields) {
      if (!f.fieldname) continue;
      if (f.fieldtype === "Link" && f.options && f.options !== m.name) put(String(f.options), row[f.fieldname], f.fieldname, f.label ?? f.fieldname, table);
      else if (f.fieldtype === "Dynamic Link" && f.options) put(String(row[String(f.options)] ?? ""), row[f.fieldname], f.fieldname, f.label ?? f.fieldname, table);
    }
  };
  scan(meta, doc);
  for (const df of meta.fields) {
    if (!df.fieldname || !TABLE_TYPES.has(df.fieldtype) || !df.options) continue;
    const cm = metaOf(String(df.options));
    if (cm) for (const r of rowsOfTable(doc, df.fieldname)) scan(cm, r, df.fieldname);
  }
  return [...out.values()];
}
