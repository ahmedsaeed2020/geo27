const metaCache = new Map<string, DocTypeMeta>();
/** Source DocPerm.permlevel for definitions whose frozen catalog rows lost it (generated by scripts/extract-permlevels.py
 *  from the raw source copy): a level-1 rule must never be read as document-level access. */
const PERM_FLAG: Record<string, string> = { a: "amend", p: "print", e: "email", s: "share", r: "report", x: "export", i: "import", l: "select", o: "if_owner", u: "set_user_permissions" };
export function withSourcePermlevels(m: DocTypeMeta): DocTypeMeta {
  const ps = m.permissions as Record<string, unknown>[] | undefined; if (!ps) return m;
  const lv = (SOURCE_PERMLEVELS as Record<string, number[]>)[m.name]; const fl = (SOURCE_PERM_FLAGS as Record<string, string[]>)[m.name];
  const useLv = !!lv && ps.length === lv.length && !ps.some((p) => "permlevel" in p);
  // the other DocPerm flags the frozen rows lost (amend, print, email, share, report, export, import, select, if_owner) — scripts/extract-permlevels.py
  const useFl = !!fl && ps.length === fl.length;
  if (!useLv && !useFl) return m;
  return { ...m, permissions: ps.map((p, i) => {
    let q = useLv && lv![i] ? { ...p, permlevel: lv![i] } : p;
    if (useFl) for (const c of fl![i] ?? "") { const k = PERM_FLAG[c]; if (k && !(k in q)) q = { ...q, [k]: 1 }; }
    return q;
  }) as DocTypeMeta["permissions"] };
}
/** Number of loaded metas (cache keys for derived data that depends on which metas are available). */
export const metaCount = () => metaCache.size;
/**
 * One request per definition file (audit G02): concurrent callers — the Pro sidebar, frame and workspace, Desk routes
 * (metaQuery) and scoped reads (ensureMetas) — share the same in-flight fetch instead of each starting their own.
 * A failed load is forgotten so the next caller retries; what is loaded is unchanged.
 */
const metaInflight = new Map<string, Promise<DocTypeMeta>>();
function fetchMeta(app: string, slug: string): Promise<DocTypeMeta> {
  const path = `/catalog/${app}/${slug}.json`;
  let p = metaInflight.get(path);
  if (!p) {
    p = j<DocTypeMeta>(path).then((raw) => { const m = raw?.name ? withSourcePermlevels(raw) : raw; if (m?.name && !metaCache.has(m.name)) metaCache.set(m.name, m); return m; });
    p.catch(() => { metaInflight.delete(path); });
    metaInflight.set(path, p);
  }
  return p;
}
export async function loadMeta(index: IndexEntry[], name: string): Promise<DocTypeMeta | undefined> {
  const e = index.find((i) => i.name === name);
  if (!e) return undefined;
  if (e.source.startsWith("plugin:")) return pluginMeta(e.slug);
  if (!metaCache.has(name)) metaCache.set(name, await fetchMeta(e.app, e.slug));
  return overlayMeta(metaCache.get(name)!);
}
/** Sync meta for the data-boundary guard: plugin DocTypes, else catalog meta already loaded this session (undefined = unknown). */
export function cachedMeta(name: string): DocTypeMeta | undefined {
  const own = pluginIndexEntries().find((e) => e.name === name); if (own) return pluginMeta(own.slug);
  const m = metaCache.get(name); return m ? overlayMeta(m) : undefined;
}
export function primeMeta(m: DocTypeMeta) { metaCache.set(m.name, withSourcePermlevels(m)); }
let indexCache: Promise<IndexEntry[]> | null = null;
/** Load catalog meta for DocTypes not yet cached (scoped reads need it to evaluate permissions for non-admin users). */
export async function ensureMetas(names: string[]): Promise<void> {
  if (!isBrowser) return;
  indexCache ??= j<IndexEntry[]>("/catalog/index.json").catch(() => { indexCache = null; return []; });
  const ix = await indexCache;
  await Promise.all(names.filter((nm) => !cachedMeta(nm)).map((nm) => loadMeta(ix, nm).catch(() => undefined)));
}
/** A DocType definition that is absent (404, or the HTML fallback page instead of JSON) will not appear on retry, so the
 *  list/form routes show "Page not found" at once; only a network failure is retried. */
export const metaMissing = (e: unknown) => /Catalog file missing|JSON|Unexpected token/i.test(String(e));
export const metaQuery = (app: string, slug: string) =>
  queryOptions({ queryKey: ["meta", app, slug, pluginsVersion()], queryFn: async () => { const own = pluginMeta(slug); if (own) return own; return overlayMeta(await fetchMeta(app, slug)); }, ...opts,
    retry: (n: number, e: unknown) => n < 3 && !metaMissing(e) });

