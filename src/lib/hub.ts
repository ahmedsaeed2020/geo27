export interface HubIndex {
  doctype: (name: string) => Pick<IndexEntry, "issingle" | "is_submittable" | "istable" | "app" | "slug"> | undefined;
  isTree: (name: string) => boolean;
  report: (name: string) => Pick<ReportEntry, "report_type" | "ref_doctype" | "roles"> | undefined;
  page?: ((name: string) => boolean) | undefined;
  app?: ((key: string) => boolean) | undefined;
  /** A child table has a register when its parents are known (src/lib/childRows.ts): its rows listed across the parents, each opening its parent. */
  childList?: ((child: string) => boolean) | undefined;
}

/** Generated by scripts/extract-engines.py: DocTypes that declare a tree view (frappe treeview settings). */
export const treeViewsQuery = queryOptions({
  queryKey: ["catalog-tree-views"],
  queryFn: async () => Object.keys(((await (await fetch("/catalog/tree_views.json")).json()) as { doctypes?: Record<string, unknown> }).doctypes ?? {}).filter((n) => !n.includes("{")),
  staleTime: Infinity,
});

export function makeHubIndex(index: IndexEntry[], reports: ReportEntry[], trees: string[], extra: Pick<HubIndex, "page" | "app" | "childList"> = {}): HubIndex {
  const byName = new Map(index.map((e) => [e.name, e]));
  const reps = new Map(reports.map((r) => [r.name, r]));
  const tset = new Set(trees);
  return { doctype: (n) => byName.get(n), isTree: (n) => tset.has(n), report: (n) => reps.get(n), ...extra };
}

const isDraftFilter = (fs: Filter[] | undefined) => !!fs?.some(([f, op, v]) => f === "docstatus" && op === "=" && String(v) === "0");
export const hubKey = (t: HubTarget) => JSON.stringify(t);

/** Group of an entry from source metadata (null = not a valid destination in this Core: dropped). */
export function classifyEntry(e: HubEntry, ix: HubIndex): { group: HubGroupId } | { drop: string } {
  const t = e.target;
  if (t.kind === "doctype" || t.kind === "tree") {
    const d = ix.doctype(t.doctype);
    if (!d) return { drop: `DocType ${t.doctype} is not installed` };
    if (d.istable) return ix.childList?.(t.doctype) ? { group: e.group ?? "related" } : { drop: `${t.doctype} is a child table without a known parent` };
    if (e.group) return { group: e.group };
    if (t.kind === "tree" || ix.isTree(t.doctype)) return { group: t.kind === "doctype" && t.filters?.length ? "daily" : "masters" };
    if (t.kind === "doctype" && t.filters?.length) return { group: isDraftFilter(t.filters) ? "approvals" : "daily" };
    if (d.issingle) return { group: /Settings$/.test(t.doctype) ? "settings" : "tools" };
    return { group: d.is_submittable ? "cycle" : "masters" };
  }
  if (t.kind === "report") return ix.report(t.report) || e.group === "custom-reports" ? { group: e.group ?? "reports" } : { drop: `Report ${t.report} is not installed` };
  if (t.kind === "page") return !ix.page || ix.page(t.page) ? { group: e.group ?? "tools" } : { drop: `Page ${t.page} is not registered` };
  return !ix.app || ix.app(t.key) ? { group: e.group ?? "app-screens" } : { drop: `Screen ${t.key} is not available` };
}

export interface HubModel { groups: HubGroup[]; dropped: { entry: HubEntry; reason: string }[]; doctypes: string[] }
/** Classify, de-duplicate (first occurrence wins) and order entries into the hub groups; empty groups are omitted. */
export function buildHub(entries: HubEntry[], ix: HubIndex): HubModel {
  // first occurrence keeps its position and label; an explicit source/domain group declared by a later duplicate
  // (a native "Setup" card, the department setup list) wins over the metadata inference of the first
  const uniq = new Map<string, HubEntry>();
  for (const e of entries) {
    const k = hubKey(e.target); const cur = uniq.get(k);
    if (!cur) uniq.set(k, e); else if (!cur.group && e.group) uniq.set(k, { ...cur, group: e.group });
  }
  const by = new Map<HubGroupId, HubEntry[]>(); const dropped: HubModel["dropped"] = []; const dts = new Set<string>();
  for (const e of uniq.values()) {
    const c = classifyEntry(e, ix);
    if ("drop" in c) { dropped.push({ entry: e, reason: c.drop }); continue; }
    by.set(c.group, [...(by.get(c.group) ?? []), e]);
    if (e.target.kind === "doctype" || e.target.kind === "tree") dts.add(e.target.doctype);
  }
  return { groups: HUB_GROUPS.filter((g) => by.get(g.id)?.length).map((g) => ({ ...g, entries: by.get(g.id)! })), dropped, doctypes: [...dts] };
}

/** Installed custom reports (Report records with is_standard = "No", enabled) over the given DocTypes or base reports. */
export function customReportEntries(doctypes: Iterable<string>, baseReports: Iterable<string> = []): HubEntry[] {
  const dts = new Set(doctypes); const bases = new Set(baseReports);
  return adapter.list("Report")
    .filter((r) => r["is_standard"] === "No" && !Number(r["disabled"] ?? 0) && (dts.has(String(r["ref_doctype"] ?? "")) || bases.has(String(r["reference_report"] ?? ""))))
    .map((r) => ({ label: String(r["report_name"] ?? r.name), target: { kind: "report" as const, report: r.name }, group: "custom-reports" as const, source: "site:Report" }));
}
